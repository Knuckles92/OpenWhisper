"""What the live API and MCP may ask the running app to do.

The desktop app registers an ``AppControl`` at startup
(``services/automation/app_control.py``); the in-app listener calls it from
its own thread. Every method may be called from any thread and returns within
about two seconds.
"""

from __future__ import annotations

import threading
from dataclasses import dataclass
from typing import Optional, Protocol

#: ``ControlError.code`` values.
BUSY = "busy"
NOT_FOUND = "not_found"
UNAVAILABLE = "unavailable"
REFUSED = "refused"


class ControlError(Exception):
    """A refusal the API reports as-is; the message names no internals."""

    def __init__(self, code: str, message: str) -> None:
        self.code = code
        self.message = message
        super().__init__(message)


@dataclass(frozen=True)
class LiveState:
    recording: bool
    busy: bool
    meeting: bool
    mode: str
    action_id: str
    job_id: str
    version: str
    meeting_state: Optional[dict] = None
    walkthrough_state: Optional[dict] = None

    def to_dict(self) -> dict:
        data = {
            "recording": self.recording,
            "busy": self.busy,
            "meeting": self.meeting,
            "mode": self.mode,
            "action_id": self.action_id or None,
            "job_id": self.job_id or None,
            "version": self.version,
        }
        if self.meeting_state is not None:
            data["meeting_state"] = self.meeting_state
        if self.walkthrough_state is not None:
            data["walkthrough_state"] = self.walkthrough_state
        return data


class AppControl(Protocol):
    def state(self) -> LiveState: ...

    def list_actions(self) -> list[dict]: ...

    def run_action(self, action_id: str, text: str, *, source: str) -> str: ...

    def start_recording(
        self,
        *,
        action_id: str = "",
        profile_id: str = "",
        route: bool = False,
        source: str,
    ) -> str: ...

    def stop_recording(self) -> None: ...

    def cancel(self) -> None: ...

    def notify(self, text: str, *, title: str = "") -> None: ...

    # ---- Profiles, transforms & file transcription ----
    def list_profiles(self) -> list[dict]: ...
    def list_transforms(self) -> list[dict]: ...
    def run_transform(self, transform_id: str, text: str, *, source: str) -> str: ...
    def transcribe_audio_file(self, path: str, *, language: Optional[str] = None, source: str = "mcp") -> dict: ...

    # ---- Meeting Mode ----
    def meeting_status(self) -> dict: ...
    def start_meeting(self, *, title: str = "", cloud: Optional[bool] = None, source: str = "mcp") -> dict: ...
    def pause_meeting(self) -> dict: ...
    def resume_meeting(self) -> dict: ...
    def end_meeting(self) -> dict: ...
    def background_meeting(self) -> dict: ...
    def retry_meeting_finalization(self, *, step: str = "failed", meeting_id: Optional[str] = None) -> dict: ...
    def manage_recovered_meeting(self, meeting_id: str, action: str) -> dict: ...
    def open_meeting_view(self, *, meeting_id: str = "", view: str = "dashboard") -> dict: ...

    # ---- Walkthroughs & screenshots ----
    def walkthrough_status(self) -> dict: ...
    def start_walkthrough(self, *, snap_mode: str = "", auto_mode: Optional[bool] = None, source: str = "mcp") -> dict: ...
    def finish_walkthrough(self) -> dict: ...
    def cancel_walkthrough(self) -> dict: ...
    def set_walkthrough_paused(self, paused: bool) -> dict: ...
    def snap_walkthrough(self, *, snap_mode: str = "", source: str = "mcp") -> dict: ...
    def choose_walkthrough_snap_mode(self, mode: str) -> dict: ...
    def edit_walkthrough_shots(self, action: str, *, number: Optional[int] = None, step: Optional[int] = None) -> dict: ...
    def take_screenshot(self, *, source: str = "mcp") -> dict: ...
    def list_walkthroughs(self, *, q: str = "", limit: int = 20) -> dict: ...
    def get_walkthrough(self, ref: str, *, spoken: bool = False, include_images: bool = False) -> dict: ...
    def run_walkthrough_writeup(self, ref: str, *, style: str = "") -> dict: ...

    # ---- Personalization ----
    def get_personalization_summary(self) -> dict: ...
    def list_dictionary(self) -> dict: ...
    def add_dictionary_term(self, term: str, *, heard: tuple[str, ...] = (), starred: bool = False) -> dict: ...
    def bulk_add_dictionary_terms(self, items: list[dict], *, dry_run: bool = False) -> dict: ...
    def remove_dictionary_term(self, term_or_id: str) -> dict: ...
    def list_snippets(self) -> dict: ...
    def upsert_snippet(self, trigger: str, text: str, *, snippet_id: str = "", formatted: bool = False) -> dict: ...
    def bulk_upsert_snippets(self, items: list[dict], *, dry_run: bool = False, skip_existing: bool = True) -> dict: ...
    def delete_snippet(self, snippet_id: str) -> dict: ...
    def get_app_styles(self) -> dict: ...
    def set_app_style_tone(self, category: str, tone: str) -> dict: ...
    def set_app_style_override(self, match: str, category: str) -> dict: ...
    def remove_app_style_override(self, match: str) -> dict: ...
    def list_walkthrough_styles(self) -> dict: ...
    def upsert_walkthrough_style(self, name: str, instructions: str) -> dict: ...
    def delete_walkthrough_style(self, style_id: str) -> dict: ...
    def list_languages(self) -> dict: ...
    def set_active_language(self, code: str) -> dict: ...
    def set_quick_record_profile(self, profile_id: str) -> dict: ...

    # ---- Learned cleanup rules ----
    def list_cleanup_rules(self) -> dict: ...
    def add_cleanup_rule(self, rule: str, *, dry_run: bool = False) -> dict: ...
    def update_cleanup_rule(self, index: int, rule: str) -> dict: ...
    def remove_cleanup_rule(self, *, index: Optional[int] = None, rule: str = "") -> dict: ...

    # ---- Engines, models, audio devices, remote & window ----
    def engine_status(self) -> dict: ...
    def list_models(self) -> dict: ...
    def select_model(self, engine: str, *, model: str = "") -> dict: ...
    def download_model(self, model_name: str) -> dict: ...
    def list_audio_devices(self) -> dict: ...
    def select_audio_device(self, name: str, *, hostapi: str = "") -> dict: ...
    def remote_status(self) -> dict: ...
    def reconnect_remote(self) -> dict: ...
    def control_window(self, action: str, *, text: str = "", tab: str = "") -> dict: ...


_control: Optional[AppControl] = None
_lock = threading.Lock()


def set_app_control(control: Optional[AppControl]) -> None:
    global _control
    with _lock:
        _control = control


def app_control() -> Optional[AppControl]:
    with _lock:
        return _control


def require_app_control() -> AppControl:
    control = app_control()
    if control is None:
        raise ControlError(UNAVAILABLE, "OpenWhisper isn't ready for this yet.")
    return control
